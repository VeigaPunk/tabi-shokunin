#!/usr/bin/env node
// CritC3Gaming scratch harness, round 4:
//  S14: the lane's committed tree + 23 refetch JSONs derived FROM THE RECEIPT (no network, no new bytes).
//  S15: a row whose Chromium tag lives only in the anchor cell leaves the population silently.
import { spawnSync } from "node:child_process";
import { mkdtempSync, mkdirSync, writeFileSync, rmSync, cpSync, readFileSync } from "node:fs";
import { join, dirname } from "node:path";

const S = process.env.S;
const LANE = join(S, "lane");
const COUNTER = join(LANE, "scripts/check-release-pins.mjs");
const OLD = "154.0.8037.97";
const NEW = "156.0.8078.47";
const REG = "corpus/SOURCES.md";
const RECEIPT = "corpus/evidence/round-29/release-pins/receipt.json";
const BYTES = "corpus/evidence/round-29/release-pins/bytes";
const REFETCH = "corpus/evidence/round-29/release-pins/refetch";

function fixture(name) {
  const root = mkdtempSync(join(S, `fx4-${name}-`));
  const g = (args) => {
    const r = spawnSync("git", ["-C", root, ...args], { encoding: "utf8" });
    if (r.status !== 0) throw new Error(`git ${args[0]} failed: ${r.stderr}`);
    return r.stdout;
  };
  g(["init", "-q"]);
  if (g(["rev-parse", "--show-toplevel"]).trim() !== root) throw new Error("fixture root mismatch");
  g(["config", "user.email", "fixture@tabi.local"]);
  g(["config", "user.name", "tabi-fixture"]);
  const put = (rel, data) => { const abs = join(root, rel); mkdirSync(dirname(abs), { recursive: true }); writeFileSync(abs, data); };
  return { root, put, commit() { g(["add", "-A"]); g(["commit", "--allow-empty", "-q", "-m", name]); return g(["rev-parse", "HEAD"]).trim(); } };
}
function run(fx, rev) {
  const r = spawnSync("node", [COUNTER, "--repo", fx.root, "--rev", rev, "--stable", NEW, "--json"], { encoding: "utf8" });
  let out = null; try { out = JSON.parse(r.stdout); } catch { out = null; }
  return { exit: r.status, population: out?.population ?? null, unresolved: out?.unresolved ?? null, holds: out?.holds ?? null, drifted: out?.drifted ?? null,
    rows: out?.rows ? out.rows.map((x) => ({ id: x.id, resolved: x.resolved, verdict: x.verdict, reasons: x.reasons })) : null, stderr: r.stderr.trim() };
}
const out = {};

// ---------------- S14: real committed tree, receipt-derived refetch only ----------------
{
  const fx = fixture("s14");
  for (const rel of [REG, RECEIPT]) cpSync(join(LANE, rel), join(fx.root, rel), { recursive: true });
  cpSync(join(LANE, BYTES), join(fx.root, BYTES), { recursive: true });
  const rec = JSON.parse(readFileSync(join(LANE, RECEIPT), "utf8"));
  for (const row of rec.rows) {
    fx.put(`${REFETCH}/${row.id}.json`, `${JSON.stringify({
      id: row.id,
      seat: "seat-name-invented-by-the-receipt-author",
      fetched_at: "1970-01-01T00:00:00Z",
      files: row.files.map((f) => ({ path: f.path, tag: NEW, status: f.new_status, sha256: f.new_sha256 })),
    }, null, 2)}\n`);
  }
  const head = fx.commit();
  const r = run(fx, head);
  const drifted = r.rows ? r.rows.filter((x) => x.verdict === "drifted").map((x) => x.id) : null;
  out.S14_receipt_derived_refetch_on_committed_tree = {
    desc: "no network, no new bytes: the 23 refetch files are generated by copying receipt.new_sha256; fetched_at is 1970, seat invented",
    ...r, driftedIds: drifted,
  };
  rmSync(fx.root, { recursive: true, force: true });
}

// ---------------- S15: tag only in the anchor cell => row leaves the population ----------------
{
  const fx = fixture("s15");
  let reg = readFileSync(join(LANE, REG), "utf8");
  const rec = JSON.parse(readFileSync(join(LANE, RECEIPT), "utf8"));
  rec.rows = rec.rows.filter((x) => x.id !== "S105");
  for (const rel of [BYTES]) cpSync(join(LANE, rel), join(fx.root, rel), { recursive: true });
  for (const rel of [REG, RECEIPT]) cpSync(join(LANE, rel), join(fx.root, rel), { recursive: true });
  for (const row of rec.rows) {
    fx.put(`${REFETCH}/${row.id}.json`, `${JSON.stringify({ id: row.id, seat: "RivalSeat", fetched_at: "x",
      files: row.files.map((f) => ({ path: f.path, tag: NEW, status: f.new_status, sha256: f.new_sha256 })) })}\n`);
  }
  const fakePath = "attacker/fixture.cc";
  const body = "x\ny\nz\n";
  const { createHash } = await import("node:crypto");
  const sh = createHash("sha256").update(body).digest("hex");
  fx.put(`${BYTES}/${OLD}/${fakePath}`, body);
  fx.put(`${BYTES}/${NEW}/${fakePath}`, body);
  fx.put(`${REFETCH}/S999.json`, `${JSON.stringify({ id: "S999", seat: "RivalSeat", fetched_at: "x", files: [{ path: fakePath, tag: NEW, status: 200, sha256: sh }] })}\n`);
  rec.rows.push({ id: "S999", fetched_by: "Attacker", files: [{ path: fakePath, old_tag: OLD, old_status: 200, new_status: 200, old_bytes: `${BYTES}/${OLD}/${fakePath}`, new_bytes: `${BYTES}/${NEW}/${fakePath}`, old_sha256: sh, new_sha256: sh, ranges: [[2, 2]] }] });
  fx.put(RECEIPT, `${JSON.stringify(rec, null, 2)}\n`);
  // S105: strip refs/tags/<154>/ from its source cell; the anchor already says "tag 154.0.8037.97"
  const line = reg.split("\n").find((l) => /^ {0,3}\|\s*S105\s*\|/.test(l));
  const cells = line.split("|").map((c) => c.trim());
  cells[2] = cells[2].replace(`refs/tags/${OLD}/`, "b510e9d7cd3a2fbd78d0ddc42234103206c5f78d/");
  const s999 = `| ${["S999", `Fixture — https://chromium.googlesource.com/chromium/src/+/refs/tags/${OLD}/attacker/fixture.cc?format=TEXT`, "code", "C", "scope", "fixture.cc:2-2", "teaches", "mined", "2026-10-20", "on-release", "—"].join(" | ")} |`;
  reg = reg.replace(line, `| ${cells.slice(1, -1).join(" | ")} |`).replace(/\n$/, `\n${s999}\n`);
  fx.put(REG, reg);
  const head = fx.commit();
  out.S15_anchor_only_tag_swap = { desc: "S105's source cell loses refs/tags/<154>/ (the anchor still carries the tag); S999 appended", ...run(fx, head) };
  rmSync(fx.root, { recursive: true, force: true });
}

console.log(JSON.stringify(out, null, 2));
