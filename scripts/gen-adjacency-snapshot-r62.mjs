#!/usr/bin/env node
// gen-adjacency-snapshot-r62.mjs — tabi round 62, C1 instrument.
// Writes the frozen sibling snapshot TSV at the documented grammar:
//   header: lane<TAB>head   (exactly two cells; the r61 generator bug that
//   processed the header as a lane and emitted an empty second cell — r61
//   lesson Mistakes 2, kill K4 — is fixed at the source and asserted here)
//   rows:   <lane><TAB><full head sha>  for every sibling lane at --fleet
//           (non-dot entries that are directories or symlinks to directories,
//           the v11 host-shape rule; SELF_LANE excluded), sorted by lane.
// A head that does not resolve to a commit is a hard refusal (exit 4): the
// generator never writes an empty or dangling head cell.
// Usage: node gen-adjacency-snapshot-r62.mjs --fleet <ABS fleet root> --out <ABS file>
//        node gen-adjacency-snapshot-r62.mjs --self-test
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const SELF_LANE = 'tabi-shokunin';

function rosterScan(fleet) {
  // v11 host-shape rule, mirrored from the meter: a lane is a non-dot entry
  // that is a directory (or a symlink to one) AND carries its own .git or
  // HEAD. The fleet root itself is a git worktree, so `git -C <dir>` resolves
  // for ANY child directory and would let plain infra dirs (research/,
  // scripts/, templates/, tools/) masquerade as lanes — never trust rev-parse
  // alone (r62 round-open observation; the meter's rosterScan has the same
  // guard).
  const laneExists = (name) => fs.existsSync(path.join(fleet, name, '.git')) || fs.existsSync(path.join(fleet, name, 'HEAD'));
  return fs.readdirSync(fleet, { withFileTypes: true })
    .filter((d) => !d.name.startsWith('.'))
    .filter((d) => {
      if (d.isDirectory()) return true;
      if (!d.isSymbolicLink()) return false;
      try { return fs.statSync(path.join(fleet, d.name)).isDirectory(); } catch { return false; }
    })
    .map((d) => d.name)
    .filter((name) => laneExists(name) && name !== SELF_LANE)
    .sort();
}

function headOf(fleet, lane) {
  const r = spawnSync('git', ['-C', path.join(fleet, lane), 'rev-parse', 'HEAD'], { encoding: 'utf8' });
  if (r.status !== 0 || !/^[0-9a-f]{40}$/.test((r.stdout || '').trim())) return null;
  return r.stdout.trim();
}

function die(code, msg, extra = {}) {
  console.error(JSON.stringify({ schema: 'tabi-adjacency-r62-snapshot-gen', error: msg, ...extra }, null, 1));
  process.exit(code);
}

function assertHeader(bytes) {
  const lines = bytes.toString('utf8').split('\n');
  if (lines[0] !== 'lane\thead') return 'header must be exactly lane TAB head';
  if (lines.length < 3) return 'no data rows';
  for (const [i, l] of lines.slice(1).entries()) {
    if (l === '' && i === lines.length - 2) break;
    const cells = l.split('\t');
    if (cells.length !== 2 || cells[0].length === 0 || !/^[0-9a-f]{40}$/.test(cells[1])) {
      return `row ${i + 2} malformed`;
    }
  }
  return null;
}

const argv = process.argv.slice(2);
if (argv[0] === '--self-test') {
  const results = [];
  const check = (name, ok, evidence) => results.push({ name, ok, evidence });
  const good = Buffer.from('lane\thead\na-shokunin\t' + 'a'.repeat(40) + '\n', 'utf8');
  const badHeader = Buffer.from('lane\t\na-shokunin\t' + 'a'.repeat(40) + '\n', 'utf8');
  const shortHead = Buffer.from('lane\thead\na-shokunin\tabc\n', 'utf8');
  check('valid-header-accepted', assertHeader(good) === null, { header: 'lane TAB head' });
  check('r61-blank-cell-refused', assertHeader(badHeader) !== null, assertHeader(badHeader));
  check('short-head-refused', assertHeader(shortHead) !== null, assertHeader(shortHead));
  const allPass = results.every((r) => r.ok);
  console.log(JSON.stringify({ schema: 'tabi-adjacency-r62-snapshot-gen-selftest', allPass, results }, null, 1));
  process.exit(allPass ? 0 : 1);
}
let fleet = null, out = null;
for (let i = 0; i < argv.length; i++) {
  if (argv[i] === '--fleet') fleet = argv[++i];
  else if (argv[i] === '--out') out = argv[++i];
}
if (!fleet || !out || !path.isAbsolute(fleet) || !path.isAbsolute(out)) {
  die(2, 'usage: node gen-adjacency-snapshot-r62.mjs --fleet <ABS> --out <ABS> | --self-test');
}
const lanes = rosterScan(fleet);
const rows = [];
const unresolved = [];
for (const lane of lanes) {
  const head = headOf(fleet, lane);
  if (head === null) unresolved.push(lane);
  else rows.push(lane + '\t' + head);
}
if (unresolved.length > 0) die(4, 'unresolvable heads: the generator writes no dangling snapshot', { unresolved });
const bytes = Buffer.from('lane\thead\n' + rows.join('\n') + '\n', 'utf8');
const headerError = assertHeader(bytes);
if (headerError !== null) die(5, 'generated bytes failed the grammar assertion: ' + headerError);
fs.writeFileSync(out, bytes);
console.log(JSON.stringify({ schema: 'tabi-adjacency-r62-snapshot-gen', out, lanes: rows.length, sha256: (await import('node:crypto')).createHash('sha256').update(bytes).digest('hex') }));
